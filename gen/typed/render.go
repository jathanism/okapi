package typed

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// pathTemplateParam matches "{name}" in URL path templates, e.g.
// "/v1/accounts/{aid}/contacts/{id}" → ["aid", "id"].
var pathTemplateParam = regexp.MustCompile(`\{([^}]+)\}`)

// pathParamOrder returns the path-template parameter names in the
// order they appear in the path. Used to render method signatures so
// path args match the URL left-to-right.
func pathParamOrder(template string) []string {
	matches := pathTemplateParam.FindAllStringSubmatch(template, -1)
	out := make([]string, 0, len(matches))
	for _, m := range matches {
		out = append(out, m[1])
	}
	return out
}

const fileHeader = `// Code generated by okapi-gen-typed. DO NOT EDIT.
//
// Source: %s

package %s

`

func (g *generator) renderTypes() (string, error) {
	var b strings.Builder
	src := g.opts.Source
	if src == "" {
		src = "<inline bytes>"
	}
	fmt.Fprintf(&b, fileHeader, src, g.opts.PackageName)

	// Per-component schema in declaration-stable order (keys sorted).
	for _, name := range g.schemaKeys {
		t := g.schemas[name]
		if t == nil {
			continue
		}
		switch t.Kind {
		case kindStruct:
			renderDoc(&b, t.Doc)
			fmt.Fprintf(&b, "type %s struct {\n", name)
			for _, f := range t.Fields {
				renderFieldDoc(&b, f.Doc)
				goType := f.GoType
				if f.Pointer {
					goType = "*" + goType
				}
				tag := fmt.Sprintf("`json:\"%s%s\"`", f.JSONName, omit(f.OmitEmpty))
				fmt.Fprintf(&b, "\t%s %s %s\n", f.GoName, goType, tag)
			}
			b.WriteString("}\n\n")
		case kindEnum:
			renderDoc(&b, t.Doc)
			fmt.Fprintf(&b, "type %s string\n\n", name)
			b.WriteString("const (\n")
			for _, v := range t.EnumValues {
				ident := goEnumIdent(name, v)
				fmt.Fprintf(&b, "\t%s %s = %q\n", ident, name, v)
			}
			b.WriteString(")\n\n")
		case kindAlias, kindArray, kindMap, kindPrimitive:
			renderDoc(&b, t.Doc)
			fmt.Fprintf(&b, "type %s %s\n\n", name, t.goExpr)
		case kindAny:
			renderDoc(&b, t.Doc)
			fmt.Fprintf(&b, "type %s = any\n\n", name)
		}
	}

	return b.String(), nil
}

func (g *generator) renderClient() (string, error) {
	var b strings.Builder
	src := g.opts.Source
	if src == "" {
		src = "<inline bytes>"
	}
	fmt.Fprintf(&b, fileHeader, src, g.opts.PackageName)

	b.WriteString(`import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strconv"
	"strings"
)

// Client is the typed HTTP client for the generated API.
type ` + g.opts.ClientName + ` struct {
	// BaseURL is prepended to every request path (no trailing slash).
	BaseURL string
	// HTTP is the underlying HTTP client. nil falls back to http.DefaultClient.
	HTTP *http.Client
	// DefaultHeaders are merged onto every request before per-call headers.
	DefaultHeaders http.Header
}

// New` + g.opts.ClientName + ` returns a Client targeting baseURL.
func New` + g.opts.ClientName + `(baseURL string) *` + g.opts.ClientName + ` {
	return &` + g.opts.ClientName + `{BaseURL: strings.TrimRight(baseURL, "/")}
}

// APIError is returned for non-2xx responses. It captures the HTTP
// status, the raw response body, and any decoded JSON payload.
type APIError struct {
	StatusCode int
	Status     string
	Method     string
	URL        string
	Body       []byte
}

func (e *APIError) Error() string {
	if len(e.Body) > 0 {
		return fmt.Sprintf("%s %s: %s: %s", e.Method, e.URL, e.Status, string(e.Body))
	}
	return fmt.Sprintf("%s %s: %s", e.Method, e.URL, e.Status)
}

// httpClient returns c.HTTP or http.DefaultClient.
func (c *` + g.opts.ClientName + `) httpClient() *http.Client {
	if c.HTTP != nil {
		return c.HTTP
	}
	return http.DefaultClient
}

// do is the shared transport for every typed method. Its signature is
// what couples the generated methods to the manual transport plumbing —
// keep it stable.
func (c *` + g.opts.ClientName + `) do(
	ctx context.Context,
	method, pathTemplate string,
	pathParams map[string]string,
	query url.Values,
	headers http.Header,
	body any,
	out any,
) error {
	path := pathTemplate
	for k, v := range pathParams {
		// OpenAPI path params are single-segment values, so we escape "/"
		// in addition to what url.PathEscape covers — otherwise an id
		// like "a/b" would route to a sibling segment.
		escaped := strings.ReplaceAll(url.PathEscape(v), "/", "%2F")
		path = strings.ReplaceAll(path, "{"+k+"}", escaped)
	}
	full := c.BaseURL + path
	if len(query) > 0 {
		full += "?" + query.Encode()
	}

	var reader io.Reader
	if body != nil {
		buf, err := json.Marshal(body)
		if err != nil {
			return fmt.Errorf("encode body: %w", err)
		}
		reader = bytes.NewReader(buf)
	}

	req, err := http.NewRequestWithContext(ctx, method, full, reader)
	if err != nil {
		return err
	}
	for k, vv := range c.DefaultHeaders {
		for _, v := range vv {
			req.Header.Add(k, v)
		}
	}
	for k, vv := range headers {
		for _, v := range vv {
			req.Header.Set(k, v)
		}
	}
	if body != nil && req.Header.Get("Content-Type") == "" {
		req.Header.Set("Content-Type", "application/json")
	}
	if req.Header.Get("Accept") == "" {
		req.Header.Set("Accept", "application/json")
	}

	resp, err := c.httpClient().Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read response: %w", err)
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return &APIError{
			StatusCode: resp.StatusCode,
			Status:     resp.Status,
			Method:     method,
			URL:        full,
			Body:       respBody,
		}
	}

	if out == nil || len(respBody) == 0 {
		return nil
	}
	if err := json.Unmarshal(respBody, out); err != nil {
		return fmt.Errorf("decode response: %w", err)
	}
	return nil
}

// formatPathValue renders a primitive into a path/query string. Enums
// are stringly typed in the generated code so this works for them too.
func formatPathValue(v any) string {
	switch x := v.(type) {
	case string:
		return x
	case int:
		return strconv.Itoa(x)
	case int32:
		return strconv.FormatInt(int64(x), 10)
	case int64:
		return strconv.FormatInt(x, 10)
	case bool:
		return strconv.FormatBool(x)
	case float32:
		return strconv.FormatFloat(float64(x), 'f', -1, 32)
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case fmt.Stringer:
		return x.String()
	default:
		return fmt.Sprint(v)
	}
}

`)

	// Per-operation: typed method with positional args.
	for _, op := range g.operations {
		renderOpMethod(&b, op, g.opts.ClientName)
	}

	return b.String(), nil
}

// orderedArg is one positional argument to a generated method, with
// the local-variable name used inside the method body and the metadata
// needed to wire it to path/query/header maps.
type orderedArg struct {
	ArgName  string // local variable name inside the function (camelCase, escaped)
	GoType   string // type expression as it appears in the signature
	WireName string // header / query / path key on the wire
	In       string // "path" / "query" / "header" / "body"
	Required bool
}

// orderArgs returns the operation's positional argument list in
// canonical order: path params (in URL-template order), then header
// params (alphabetical), then query params (alphabetical), then the
// request body if any. This ordering is mechanical and stable across
// regens — adding a new query/header field doesn't reshuffle existing
// args.
func orderArgs(op *operation) []orderedArg {
	byKey := map[string]*paramField{}
	for _, p := range op.Params {
		byKey[p.In+"\x00"+p.WireName] = p
	}

	var out []orderedArg

	// Path params in URL-template order.
	for _, name := range pathParamOrder(op.Path) {
		p, ok := byKey["path\x00"+name]
		if !ok {
			continue
		}
		out = append(out, argFromParam(p))
	}

	// Header params, alphabetical by Go name (deterministic and
	// independent of spec field order).
	headers := []*paramField{}
	queries := []*paramField{}
	for _, p := range op.Params {
		switch p.In {
		case "header":
			headers = append(headers, p)
		case "query":
			queries = append(queries, p)
		}
	}
	sort.Slice(headers, func(i, j int) bool { return headers[i].GoName < headers[j].GoName })
	sort.Slice(queries, func(i, j int) bool { return queries[i].GoName < queries[j].GoName })
	for _, p := range headers {
		out = append(out, argFromParam(p))
	}
	for _, p := range queries {
		out = append(out, argFromParam(p))
	}

	if op.HasBody {
		goType := op.BodyType
		if op.BodyPtr {
			goType = "*" + goType
		}
		out = append(out, orderedArg{
			ArgName:  "body",
			GoType:   goType,
			In:       "body",
			Required: op.BodyReq,
		})
	}

	return out
}

func argFromParam(p *paramField) orderedArg {
	goType := p.GoType
	if !p.Required {
		goType = "*" + goType
	}
	return orderedArg{
		ArgName:  safeArgName(p.GoName),
		GoType:   goType,
		WireName: p.WireName,
		In:       p.In,
		Required: p.Required,
	}
}

func renderOpMethod(b *strings.Builder, op *operation, clientName string) {
	args := orderArgs(op)

	// Doc
	if op.Doc != "" {
		for _, line := range strings.Split(op.Doc, "\n") {
			fmt.Fprintf(b, "// %s\n", line)
		}
	}

	// Signature.
	var sigArgs []string
	sigArgs = append(sigArgs, "ctx context.Context")
	for _, a := range args {
		sigArgs = append(sigArgs, fmt.Sprintf("%s %s", a.ArgName, a.GoType))
	}
	ret := "error"
	if op.HasResult {
		ret = fmt.Sprintf("(*%s, error)", strings.TrimPrefix(op.ResultType, "*"))
	}
	fmt.Fprintf(b, "func (c *%s) %s(%s) %s {\n",
		clientName, op.GoName, strings.Join(sigArgs, ", "), ret)

	// Locals for path/query/header.
	b.WriteString("\tpathParams := map[string]string{}\n")
	b.WriteString("\tquery := url.Values{}\n")
	b.WriteString("\theaders := http.Header{}\n")
	b.WriteString("\t_ = pathParams\n\t_ = query\n\t_ = headers\n")

	for _, a := range args {
		if a.In == "body" {
			continue
		}
		valExpr := a.ArgName
		if !a.Required {
			fmt.Fprintf(b, "\tif %s != nil {\n", a.ArgName)
			valExpr = "*" + a.ArgName
		}
		switch a.In {
		case "path":
			fmt.Fprintf(b, "\t\tpathParams[%q] = formatPathValue(%s)\n", a.WireName, valExpr)
		case "query":
			fmt.Fprintf(b, "\t\tquery.Set(%q, formatPathValue(%s))\n", a.WireName, valExpr)
		case "header":
			fmt.Fprintf(b, "\t\theaders.Set(%q, formatPathValue(%s))\n", a.WireName, valExpr)
		}
		if !a.Required {
			b.WriteString("\t}\n")
		}
	}

	// Body / result / do().
	bodyArg := "nil"
	if op.HasBody {
		bodyArg = "body"
	}
	resultArg := "nil"
	if op.HasResult {
		b.WriteString("\tvar out " + strings.TrimPrefix(op.ResultType, "*") + "\n")
		resultArg = "&out"
	}

	fmt.Fprintf(b,
		"\tif err := c.do(ctx, %q, %q, pathParams, query, headers, %s, %s); err != nil {\n",
		op.Method, op.Path, bodyArg, resultArg,
	)
	if op.HasResult {
		b.WriteString("\t\treturn nil, err\n\t}\n")
		b.WriteString("\treturn &out, nil\n")
	} else {
		b.WriteString("\t\treturn err\n\t}\n")
		b.WriteString("\treturn nil\n")
	}
	b.WriteString("}\n\n")
}

func renderDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		fmt.Fprintf(b, "// %s\n", line)
	}
}

func renderFieldDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	// Inline field doc as a single-line comment for legibility in output.
	first := strings.SplitN(doc, "\n", 2)[0]
	fmt.Fprintf(b, "\t// %s\n", first)
}

func omit(b bool) string {
	if b {
		return ",omitempty"
	}
	return ""
}
