package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"text/template"

	"github.com/jathanism/okapi"
	"github.com/jathanism/okapi/internal/log"
	"github.com/jathanism/okapi/spec"
)

const openapiTemplate = `// This file is generated by gen/gen.go - DO NOT EDIT
package openapi

type OpenApi struct {
	internal  // Internal fields from openapi.go

{{ range . }}	{{ . }} OpenApiEndpoint
{{end}}}
`

const openFlags = os.O_WRONLY | os.O_TRUNC | os.O_CREATE

func main() {
	var err error
	var api *openapi.OpenApi

	// Flags for the code generator
	defaultHost := flag.String("host", "", "Default API host (e.g. api.example.com)")
	source := flag.String("source", "", "OpenAPI spec source URL or 'embed' for embedded schema")
	schemaDir := flag.String("schema-dir", "./cli/schema", "Output directory for embedded schema file")
	flag.Parse()

	specSource := *source
	if specSource == "" {
		specSource = os.Getenv("OKAPI_OPENAPI_SOURCE")
	}

	if specSource == "embed" {
		// Use the embedded schema file
		if api, err = (*openapi.OpenApi)(nil).NewFromBytes([]byte{}); err != nil {
			log.Fatal("embedded schema not available in standalone okapi; provide --source")
		}
	} else if specSource != "" {
		api = makeOpenApiFromSource(specSource, *schemaDir)
	} else if *defaultHost != "" {
		specSource = "https://" + *defaultHost + "/api/schema/"
		api = makeOpenApiFromSource(specSource, *schemaDir)
	} else {
		log.Fatal("specify --host or --source, or set OKAPI_OPENAPI_SOURCE")
	}

	if api == nil {
		log.Fatal("failed to build OpenApi from source: " + specSource)
	}

	// Iterate over all the endpoints to get the list of CamelCased names
	endpoints := api.Endpoints()
	names := make([]string, 0, len(endpoints))
	for _, endpoint := range endpoints {
		names = append(names, endpoint.MethodName())
	}
	sort.Strings(names)

	log.Info(fmt.Sprintf("Generating new OpenApi file with %d endpoints...", len(names)))

	writeTemplate("openapi_gen", openapiTemplate, names)
}

// makeOpenApiFromSource will build a new OpenApi from the provided source. If
// there's an error, it will panic.
func makeOpenApiFromSource(source string, schemaDir string) (api *openapi.OpenApi) {
	var err error
	log.Info("Retrieving OpenApi Schema from " + source)
	// Build a new OpenApi from the spec
	if api, err = (*openapi.OpenApi)(nil).NewFromSource(source); err != nil {
		log.Fatal(err)
	}
	// This will be cached in memory, so it's just a way to directly access the spec
	if spec, err := (*spec.OpenApiSpec)(nil).NewFromSource(source); err != nil {
		log.Fatal(err)
	} else {
		log.Info("Generating embedded schema...")
		// Update the embedded Schema
		schemaPath := schemaDir + "/openapi.yaml"
		if schema, err := os.OpenFile(schemaPath, openFlags, 0644); err != nil {
			log.Fatal(err)
		} else {
			schema.Write(spec.RawSchema)
			log.Info("Updated embedded schema: " + schemaPath)
		}
	}
	return
}

func writeTemplate(name string, content string, names []string) {
	// Build the template
	tmpl, err := template.New(name).Parse(content)
	if err != nil {
		log.Fatal(err)
	}

	// Open our generated file
	out, err := os.OpenFile("./"+name+".go", openFlags, 0644)
	if err != nil {
		log.Fatal(err)
	}
	defer out.Close()

	// Write the output
	err = tmpl.Execute(out, names)
	if err != nil {
		log.Fatal(err)
	}

	log.Info("Updated " + name + ".go")
}
