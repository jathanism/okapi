// orderedArg is one positional argument to a generated method, with
// the local-variable name used inside the method body and the metadata
// needed to wire it to path/query/header maps.
type orderedArg struct {
	ArgName  string // local variable name inside the function (camelCase, escaped)
	GoType   string // type expression as it appears in the signature
	WireName string // header / query / path key on the wire
	In       string // "path" / "query" / "header" / "body"
	Required bool
}

// orderArgs returns the operation's positional argument list in
// canonical order: path params (in URL-template order), then header
// params (alphabetical), then query params (alphabetical), then the
// request body if any. This ordering is mechanical and stable across
// regens — adding a new query/header field doesn't reshuffle existing
// args.
func orderArgs(op *operation) []orderedArg {
	byKey := map[string]*paramField{}
	for _, p := range op.Params {
		byKey[p.In+"\x00"+p.WireName] = p
	}

	var out []orderedArg

	// Path params in URL-template order.
	for _, name := range pathParamOrder(op.Path) {
		p, ok := byKey["path\x00"+name]
		if !ok {
			continue
		}
		out = append(out, argFromParam(p))
	}

	// Header params, alphabetical by Go name (deterministic and
	// independent of spec field order).
	headers := []*paramField{}
	queries := []*paramField{}
	for _, p := range op.Params {
		switch p.In {
		case "header":
			headers = append(headers, p)
		case "query":
			queries = append(queries, p)
		}
	}
	sort.Slice(headers, func(i, j int) bool { return headers[i].GoName < headers[j].GoName })
	sort.Slice(queries, func(i, j int) bool { return queries[i].GoName < queries[j].GoName })
	for _, p := range headers {
		out = append(out, argFromParam(p))
	}
	for _, p := range queries {
		out = append(out, argFromParam(p))
	}

	if op.HasBody {
		goType := op.BodyType
		if op.BodyPtr {
			goType = "*" + goType
		}
		out = append(out, orderedArg{
			ArgName:  "body",
			GoType:   goType,
			In:       "body",
			Required: op.BodyReq,
		})
	}

	return out
}

func argFromParam(p *paramField) orderedArg {
	goType := p.GoType
	if !p.Required {
		goType = "*" + goType
	}
	return orderedArg{
		ArgName:  safeArgName(p.GoName),
		GoType:   goType,
		WireName: p.WireName,
		In:       p.In,
		Required: p.Required,
	}
}

func renderOpMethod(b *strings.Builder, op *operation, clientName string) {
	args := orderArgs(op)

	// Response headers struct, declared next to the method that
	// returns it.
	if op.HeadersName != "" {
		fmt.Fprintf(b, "// %s carries the response headers declared on %s's\n", op.HeadersName, op.GoName)
		b.WriteString("// success response. Headers absent from the response are left as zero\n// values.\n")
		fmt.Fprintf(b, "type %s struct {\n", op.HeadersName)
		for _, h := range op.RespHeaders {
			renderFieldDoc(b, h.Doc)
			fmt.Fprintf(b, "\t%s %s\n", h.GoName, h.GoType)
		}
		b.WriteString("}\n\n")
	}

	// Doc: the spec's summary/description, plus streaming contracts.
	docParas := []string{}
	if op.Doc != "" {
		docParas = append(docParas, op.Doc)
	}
	if op.BodyStream {
		docParas = append(docParas,
			fmt.Sprintf("The request body is streamed as %s; it is not buffered.", op.BodyMedia))
	}
	if op.ResultStream {
		docParas = append(docParas, fmt.Sprintf(
			"The returned io.ReadCloser streams the raw %s response body;\nthe caller must close it.",
			op.ResultMedia))
	}
	if doc := strings.Join(docParas, "\n\n"); doc != "" {
		for _, line := range strings.Split(doc, "\n") {
			fmt.Fprintf(b, "%s\n", strings.TrimRight("// "+line, " "))
		}
	}

	// Return list: result (JSON *T or streamed io.ReadCloser), then the
	// declared-headers struct, then error. zeroRets are the non-error
	// return values on the error path.
	var retTypes, zeroRets []string
	switch {
	case op.HasResult:
		retTypes = append(retTypes, "*"+strings.TrimPrefix(op.ResultType, "*"))
		zeroRets = append(zeroRets, "nil")
	case op.ResultStream:
		retTypes = append(retTypes, "io.ReadCloser")
		zeroRets = append(zeroRets, "nil")
	}
	if op.HeadersName != "" {
		retTypes = append(retTypes, op.HeadersName)
		zeroRets = append(zeroRets, op.HeadersName+"{}")
	}
	retTypes = append(retTypes, "error")
	ret := retTypes[0]
	if len(retTypes) > 1 {
		ret = "(" + strings.Join(retTypes, ", ") + ")"
	}
	errReturn := strings.Join(append(append([]string{}, zeroRets...), "err"), ", ")

	// Signature.
	var sigArgs []string
	sigArgs = append(sigArgs, "ctx context.Context")
	for _, a := range args {
		sigArgs = append(sigArgs, fmt.Sprintf("%s %s", a.ArgName, a.GoType))
	}
	fmt.Fprintf(b, "func (c *%s) %s(%s) %s {\n",
		clientName, op.GoName, strings.Join(sigArgs, ", "), ret)

	// Locals for path/query/header.
	b.WriteString("\tpathParams := map[string]string{}\n")
	b.WriteString("\tquery := url.Values{}\n")
	b.WriteString("\theaders := http.Header{}\n")
	b.WriteString("\t_ = pathParams\n\t_ = query\n\t_ = headers\n")

	for _, a := range args {
		if a.In == "body" {
			continue
		}
		valExpr := a.ArgName
		if !a.Required {
			fmt.Fprintf(b, "\tif %s != nil {\n", a.ArgName)
			valExpr = "*" + a.ArgName
		}
		switch a.In {
		case "path":
			fmt.Fprintf(b, "\t\tpathParams[%q] = formatPathValue(%s)\n", a.WireName, valExpr)
		case "query":
			fmt.Fprintf(b, "\t\tquery.Set(%q, formatPathValue(%s))\n", a.WireName, valExpr)
		case "header":
			fmt.Fprintf(b, "\t\theaders.Set(%q, formatPathValue(%s))\n", a.WireName, valExpr)
		}
		if !a.Required {
			b.WriteString("\t}\n")
		}
	}

	// Body: JSON bodies are pre-encoded so the transport only ever sees
	// an io.Reader; streamed bodies pass through with their media type.
	bodyArg := "nil"
	contentType := `""`
	switch {
	case op.HasBody && op.BodyJSON:
		fmt.Fprintf(b, "\tbodyReader, err := jsonBody(body)\n\tif err != nil {\n\t\treturn %s\n\t}\n", errReturn)
		bodyArg = "bodyReader"
		contentType = `"application/json"`
	case op.HasBody && op.BodyStream:
		bodyArg = "body"
		contentType = fmt.Sprintf("%q", op.BodyMedia)
	}
	accept := `"application/json"`
	if op.ResultStream {
		accept = fmt.Sprintf("%q", op.ResultMedia)
	}

	// Result / transport call. okRets accumulates the values returned on
	// the success path, in signature order.
	var okRets []string
	switch {
	case op.ResultStream:
		headerVar := "_"
		if op.HeadersName != "" {
			headerVar = "respHeader"
		}
		fmt.Fprintf(b,
			"\trespBody, %s, err := c.doStream(ctx, %q, %q, pathParams, query, headers, %s, %s, %s)\n",
			headerVar, op.Method, op.Path, bodyArg, contentType, accept,
		)
		fmt.Fprintf(b, "\tif err != nil {\n\t\treturn %s\n\t}\n", errReturn)
		okRets = append(okRets, "respBody")
	case op.HasResult:
		b.WriteString("\tvar out " + strings.TrimPrefix(op.ResultType, "*") + "\n")
		if op.HeadersName != "" {
			fmt.Fprintf(b,
				"\trespHeader, err := c.do(ctx, %q, %q, pathParams, query, headers, %s, %s, %s, &out)\n",
				op.Method, op.Path, bodyArg, contentType, accept,
			)
			fmt.Fprintf(b, "\tif err != nil {\n\t\treturn %s\n\t}\n", errReturn)
		} else {
			fmt.Fprintf(b,
				"\tif _, err := c.do(ctx, %q, %q, pathParams, query, headers, %s, %s, %s, &out); err != nil {\n",
				op.Method, op.Path, bodyArg, contentType, accept,
			)
			fmt.Fprintf(b, "\t\treturn %s\n\t}\n", errReturn)
		}
		okRets = append(okRets, "&out")
	default:
		if op.HeadersName != "" {
			fmt.Fprintf(b,
				"\trespHeader, err := c.do(ctx, %q, %q, pathParams, query, headers, %s, %s, %s, nil)\n",
				op.Method, op.Path, bodyArg, contentType, accept,
			)
			fmt.Fprintf(b, "\tif err != nil {\n\t\treturn %s\n\t}\n", errReturn)
		} else {
			fmt.Fprintf(b,
				"\tif _, err := c.do(ctx, %q, %q, pathParams, query, headers, %s, %s, %s, nil); err != nil {\n",
				op.Method, op.Path, bodyArg, contentType, accept,
			)
			fmt.Fprintf(b, "\t\treturn %s\n\t}\n", errReturn)
		}
	}

	// Decode declared response headers into the typed struct.
	if op.HeadersName != "" {
		fmt.Fprintf(b, "\toutHeaders := %s{}\n", op.HeadersName)
		for _, h := range op.RespHeaders {
			renderHeaderDecode(b, h)
		}
		okRets = append(okRets, "outHeaders")
	}

	okRets = append(okRets, "nil")
	fmt.Fprintf(b, "\treturn %s\n", strings.Join(okRets, ", "))
	b.WriteString("}\n\n")
}

// renderHeaderDecode emits the assignment of one wire header into its
// typed outHeaders field. Non-string primitives parse best-effort: a
// missing or malformed value leaves the field at its zero value.
func renderHeaderDecode(b *strings.Builder, h *respHeaderField) {
	get := fmt.Sprintf("respHeader.Get(%q)", h.WireName)
	switch h.Parse {
	case "cast":
		fmt.Fprintf(b, "\toutHeaders.%s = %s(%s)\n", h.GoName, h.GoType, get)
	case "int32":
		fmt.Fprintf(b, "\tif v, err := strconv.ParseInt(%s, 10, 32); err == nil {\n\t\toutHeaders.%s = int32(v)\n\t}\n", get, h.GoName)
	case "int64":
		fmt.Fprintf(b, "\tif v, err := strconv.ParseInt(%s, 10, 64); err == nil {\n\t\toutHeaders.%s = v\n\t}\n", get, h.GoName)
	case "float32":
		fmt.Fprintf(b, "\tif v, err := strconv.ParseFloat(%s, 32); err == nil {\n\t\toutHeaders.%s = float32(v)\n\t}\n", get, h.GoName)
	case "float64":
		fmt.Fprintf(b, "\tif v, err := strconv.ParseFloat(%s, 64); err == nil {\n\t\toutHeaders.%s = v\n\t}\n", get, h.GoName)
	case "bool":
		fmt.Fprintf(b, "\tif v, err := strconv.ParseBool(%s); err == nil {\n\t\toutHeaders.%s = v\n\t}\n", get, h.GoName)
	default:
		fmt.Fprintf(b, "\toutHeaders.%s = %s\n", h.GoName, get)
	}
}

func renderDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		fmt.Fprintf(b, "// %s\n", line)
	}
}

func renderFieldDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	// Inline field doc as a single-line comment for legibility in output.
	first := strings.SplitN(doc, "\n", 2)[0]
	fmt.Fprintf(b, "\t// %s\n", first)
}

func omit(b bool) string {
	if b {
		return ",omitempty"
	}
	return ""
}
